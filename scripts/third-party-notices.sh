#!/usr/bin/env bash
# Keeps THIRD_PARTY_NOTICES.md's generated section true to the NuGet packages a release carries.
#
# A release carries what restore resolved for its published targets: a package with a runtime,
# resource or native file in that target's project.assets.json entry, and .NET's own runtime pack.
# Analyzers, MSBuild tasks and NativeAOT's compiler put nothing in those entries and ship nothing.
# A package licensed by expression with no file of its own takes third_party/licenses/<expression>.txt.
#
# Usage: third-party-notices.sh generate
#        third-party-notices.sh check <cli|desktop> <notices-file>
#        third-party-notices.sh --selftest
set -euo pipefail

. "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"

readonly ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# Each overridable so --selftest can run against fixtures.
assets_root="${NOTICES_ASSETS:-artifacts/obj}"
targets_file="${NOTICES_TARGETS:-release-targets.json}"
licenses_root="${NOTICES_LICENSES:-third_party/licenses}"
notices_file="${NOTICES_FILE:-THIRD_PARTY_NOTICES.md}"
packages_root="${NUGET_PACKAGES:-$HOME/.nuget/packages}"

readonly BEGIN_MARK='<!-- BEGIN GENERATED by scripts/third-party-notices.sh; regenerate it rather than editing it. -->'
readonly END_MARK='<!-- END GENERATED -->'
readonly WINDOWS_TFM='net10.0-windows10.0.19041.0'

rids_of() {
  jq -r --arg component "$1" '.components[$component].targets[].rid' "$targets_file" | tr -d '\r'
}

# <project> <tfm> <rid> prints each package restored into that target with a file it would publish.
restored_packages() {
  jq -r --arg target "$2/$3" '
    def real(kind): [(.value[kind] // {}) | keys[] | select(endswith("_._") | not)] | length > 0;
    (.targets[$target] // error("no target \($target) in the restored project"))
    | to_entries[] | select(.value.type == "package")
    | select(real("runtime") or real("resource") or real("native"))
    | (.key | split("/")) + [if real("native") then "yes" else "no" end] | @tsv
  ' "$assets_root/$1/project.assets.json" | tr -d '\r'
}

# <project> <tfm> <pack> <native> prints a pack the SDK downloads for a publish rather than a package restore records.
sdk_pack() {
  local version
  version="$(jq -r --arg tfm "$2" --arg pack "$3" '
    [.project.frameworks[$tfm].downloadDependencies[] | select(.name == $pack) | .version] | first // empty
  ' "$assets_root/$1/project.assets.json" | tr -d '\r')"
  [ -n "$version" ] || die "$1 restored no $3 for $2, so this script no longer knows what its publish links"
  version="${version#[}"
  printf '%s\t%s\t%s\n' "$3" "${version%%,*}" "$4"
}

# The NativeAOT keypaste, in the CLI archives and beside the desktop app.
cli_packages() {
  restored_packages Keypaste.Cli net10.0 "$1"
  sdk_pack Keypaste.Cli net10.0 "Microsoft.NETCore.App.Runtime.NativeAOT.$1" yes
}

desktop_packages() {
  local tfm=net10.0
  # As app.yml publishes it: the Windows package is the Windows target.
  case "$1" in
    win-*)
      tfm="$WINDOWS_TFM"
      sdk_pack Keypaste.App "$tfm" Microsoft.Windows.SDK.NET.Ref no
      ;;
  esac
  restored_packages Keypaste.App "$tfm" "$1"
  sdk_pack Keypaste.App "$tfm" "Microsoft.NETCore.App.Runtime.$1" yes
  cli_packages "$1"
}

# <cli|desktop> prints name, version, native, and the part of the Ships in cell that product owns.
product_rows() {
  local component label rid rids=''
  case "$1" in
    cli) component=cli label=CLI ;;
    desktop) component=app label=Desktop ;;
    *) die "unknown product '$1'; expected cli or desktop" ;;
  esac
  rids="$(rids_of "$component")"
  [ -n "$rids" ] || die "$targets_file lists no targets for $component"
  for rid in $rids; do
    "$1_packages" "$rid" | sed "s/\$/$(printf '\t')$rid/"
  done | LC_ALL=C sort -u | awk -F'\t' -v OFS='\t' -v label="$label" -v total="$(printf '%s\n' "$rids" | wc -l | tr -d ' ')" '
    { key = $1 FS $2 }
    !(key in native) { order[++n] = key; native[key] = "no" }
    $3 == "yes" { native[key] = "yes" }
    { rids[key] = rids[key] (count[key]++ ? ", " : "") $4 }
    END {
      for (i = 1; i <= n; i++) {
        key = order[i]
        print key, native[key], (count[key] == total ? label : label " (" rids[key] ")")
      }
    }'
}

xml_text() { sed -e 's/&lt;/</g' -e 's/&gt;/>/g' -e 's/&quot;/"/g' -e "s/&apos;/'/g" -e 's/&amp;/\&/g'; }

nuspec_element() {
  LC_ALL=C sed -n "s:.*<$2[ >][^<]*>\\([^<]*\\)</$2>.*:\\1:p; s:.*<$2>\\([^<]*\\)</$2>.*:\\1:p" "$1" | head -1 | xml_text
}

nuspec_attribute() {
  LC_ALL=C sed -n "s:.*<$2 [^>]*$3=\"\\([^\"]*\\)\".*:\\1:p" "$1" | head -1 | xml_text
}

# One copy of a text with its encoding's accidents removed, so the same file on another platform dedupes.
normalized() { tr -d '\r' < "$1" | LC_ALL=C awk 'NR == 1 { sub(/^\357\273\277/, "") } { print }'; }

# <file> <package>: files the text under the number it already has, or a new one.
record_text() {
  local file="$1" package="$2" candidate="$work/candidate" i=1
  normalized "$file" > "$candidate"
  while [ -f "$work/text.$i" ]; do
    if cmp -s "$candidate" "$work/text.$i"; then
      grep -qxF "$package" "$work/used.$i" || printf '%s\n' "$package" >> "$work/used.$i"
      return 0
    fi
    i=$((i + 1))
  done
  mv "$candidate" "$work/text.$i"
  printf '%s\n' "$package" > "$work/used.$i"
}

flag() { echo "FLAG: $*" >&2; }

# Prints one table row for a package and records the texts it brings.
package_row() {
  local name="$1" version="$2" native="$3" ships="$4" lower dir nuspec type license url copyright project cell found=''
  lower="$(printf '%s' "$name" | tr '[:upper:]' '[:lower:]')"
  dir="$packages_root/$lower/$version"
  nuspec="$(find "$dir" -maxdepth 1 -iname '*.nuspec' 2>/dev/null | head -1)"
  [ -n "$nuspec" ] || die "$name $version is not in $packages_root; restore both solutions first"

  type="$(nuspec_attribute "$nuspec" license type)"
  license="$(nuspec_element "$nuspec" license)"
  url="$(nuspec_element "$nuspec" licenseUrl)"
  copyright="$(nuspec_element "$nuspec" copyright)"
  project="$(nuspec_element "$nuspec" projectUrl)"
  [ -n "$project" ] || project="$(nuspec_attribute "$nuspec" repository url)"

  if [ "$type" = file ] && [ -f "$dir/$license" ]; then
    record_text "$dir/$license" "$name"
    found=yes
  else
    local own
    own="$(find "$dir" -maxdepth 1 -type f \( -iname 'license' -o -iname 'license.txt' -o -iname 'license.md' \) | LC_ALL=C sort | head -1)"
    if [ -n "$own" ]; then
      record_text "$own" "$name"
      found=yes
    elif [ -n "$license" ] && [ -f "$licenses_root/$license.txt" ]; then
      record_text "$licenses_root/$license.txt" "$name"
      found=yes
    fi
  fi

  while IFS= read -r notice; do
    [ -n "$notice" ] && record_text "$notice" "$name"
  done < <(find "$dir" -maxdepth 1 -type f -iname '*notice*' | LC_ALL=C sort)

  if [ "$type" = expression ]; then
    cell="$license"
  elif [ "$type" = file ]; then
    cell="See its text below"
  elif [ -n "$url" ]; then
    cell="Terms at <$url>"
    flag "$name $version gives only a licence URL, $url"
  else
    cell='Not stated by the package'
    flag "$name $version states no licence"
  fi
  [ -n "$found" ] || flag "$name $version carries no licence text keypaste can reproduce"
  if [ -z "$copyright" ]; then
    copyright='Not stated by the package'
    flag "$name $version states no copyright holder"
  fi
  [ -n "$project" ] || project='Not stated by the package'

  printf '| %s | %s | %s | %s | %s | %s | %s |\n' \
    "$name" "$version" "$ships" "$native" "$cell" "${copyright//|/\\|}" "$project"
}

all_rows() {
  { product_rows cli; product_rows desktop; } | awk -F'\t' -v OFS='\t' '
    { key = $1 FS $2 }
    !(key in cells) { order[++n] = key; native[key] = "no"; cells[key] = "" }
    $3 == "yes" { native[key] = "yes" }
    { cells[key] = cells[key] (cells[key] == "" ? "" : "; ") $4 }
    END { for (i = 1; i <= n; i++) print order[i], native[order[i]], cells[order[i]] }
  ' | LC_ALL=C sort -f
}

generated_section() {
  local name version native ships i
  cat <<'INTRO'
## NuGet packages a release carries

This section lists every NuGet package in a release, direct or indirect: each package restore resolves with a runtime, resource or native file for a published target, and .NET's own runtime pack, which the self-contained desktop app carries and the NativeAOT `keypaste` links. A self-contained package's launcher is .NET's apphost, from the same release and under the same licence as its runtime pack. Build-only packages, such as analyzers and NativeAOT's compiler, leave nothing in a release and are not listed. Desktop includes the NativeAOT `keypaste` it carries. A row without runtime identifiers ships on every one its product publishes.

Licence texts and any third-party notices a package bundles follow the table, each distinct text once. A text under a standard expression names no holder of its own, so the table's Copyright column is the holder's notice for that package.

| Package | Version | Ships in | Native code | Licence | Copyright | Project |
|---|---|---|---|---|---|---|
INTRO
  while IFS=$'\t' read -r name version native ships; do
    package_row "$name" "$version" "$native" "$ships"
  done < "$work/rows"

  printf '\n### Licence and notice texts\n'
  i=1
  while [ -f "$work/text.$i" ]; do
    if LC_ALL=C grep -q '~~~~' "$work/text.$i"; then die "text $i holds the fence this section wraps texts in"; fi
    printf '\n#### Text %d\n\nUsed by %s.\n\n~~~~text\n' "$i" "$(LC_ALL=C sort -f "$work/used.$i" | awk 'NR > 1 { printf ", " } { printf "`%s`", $0 }')"
    cat "$work/text.$i"
    printf '~~~~\n'
    i=$((i + 1))
  done
}

generate() {
  [ -f "$notices_file" ] || die "no $notices_file"
  LC_ALL=C grep -qxF "$BEGIN_MARK" "$notices_file" && LC_ALL=C grep -qxF "$END_MARK" "$notices_file" \
    || die "$notices_file has no generated section to rewrite"
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' EXIT
  all_rows > "$work/rows"
  generated_section > "$work/section"
  {
    sed "/^$(printf '%s' "$BEGIN_MARK" | sed 's/[][\.*/]/\\&/g')\$/q" "$notices_file"
    cat "$work/section"
    printf '%s\n' "$END_MARK"
  } > "$work/notices"
  cp "$work/notices" "$notices_file"
  echo "$notices_file: $(wc -l < "$work/rows" | tr -d ' ') packages."
}

listed_rows() {
  tr -d '\r' < "$2" | awk -F' *[|] *' -v OFS='\t' -v label="$1" -v begin="$BEGIN_MARK" -v end="$END_MARK" '
    $0 == begin { inside = 1; next }
    $0 == end { inside = 0 }
    inside && NF > 4 && $3 ~ /^[0-9]/ {
      parts = split($4, ships, /; */)
      for (i = 1; i <= parts; i++) if (ships[i] ~ ("^" label "( |$)")) print $2, $3, ships[i]
    }'
}

check() {
  local product="$1" file="$2" label expected listed missing extra
  case "$product" in
    cli) label=CLI ;;
    desktop) label=Desktop ;;
    *) die "unknown product '$product'; expected cli or desktop" ;;
  esac
  [ -f "$file" ] || die "no notices file at $file"
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' EXIT
  product_rows "$product" | cut -f1,2,4 | LC_ALL=C sort -u > "$work/expected"
  listed_rows "$label" "$file" | LC_ALL=C sort -u > "$work/listed"
  [ -s "$work/expected" ] || die "found no packages for $product; was it restored?"
  [ -s "$work/listed" ] || die "$file lists no package for $label; is its generated section there?"
  missing="$(LC_ALL=C comm -23 "$work/expected" "$work/listed")"
  extra="$(LC_ALL=C comm -13 "$work/expected" "$work/listed")"
  if [ -n "$missing" ] || [ -n "$extra" ]; then
    {
      [ -z "$missing" ] || printf 'shipped but not listed:\n%s\n' "$missing"
      [ -z "$extra" ] || printf 'listed but not shipped:\n%s\n' "$extra"
    } >&2
    die "$file does not match what $product ships; run scripts/third-party-notices.sh generate"
  fi
  echo "$file: lists the $(wc -l < "$work/expected" | tr -d ' ') packages $product ships."
}

selftest() {
  dir="$(mktemp -d)"
  trap 'rm -rf "$dir"' EXIT
  local self="$ROOT/scripts/third-party-notices.sh"

  export NOTICES_ASSETS="$dir/obj" NOTICES_TARGETS="$dir/targets.json" NOTICES_LICENSES="$dir/licenses"
  export NOTICES_FILE="$dir/notices.md" NUGET_PACKAGES="$dir/nuget"
  mkdir -p "$dir/licenses" "$dir/obj/Keypaste.Cli" "$dir/obj/Keypaste.App"
  printf 'MIT text\n' > "$dir/licenses/MIT.txt"

  cat > "$dir/targets.json" <<'JSON'
{"components": {"cli": {"targets": [{"rid": "linux-x64"}, {"rid": "win-x64"}]}, "app": {"targets": [{"rid": "linux-x64"}, {"rid": "win-x64"}]}}}
JSON
  cat > "$dir/obj/Keypaste.Cli/project.assets.json" <<'JSON'
{"targets": {
  "net10.0/linux-x64": {"Cli.Dep/1.0.0": {"type": "package", "runtime": {"lib/net10.0/Cli.Dep.dll": {}}},
                        "Analyzer.Only/9.0.0": {"type": "package", "runtime": {"lib/net10.0/_._": {}}}},
  "net10.0/win-x64": {"Cli.Dep/1.0.0": {"type": "package", "runtime": {"lib/net10.0/Cli.Dep.dll": {}}},
                      "Analyzer.Only/9.0.0": {"type": "package", "runtime": {"lib/net10.0/_._": {}}}}},
 "project": {"frameworks": {"net10.0": {"downloadDependencies": [
   {"name": "Microsoft.NETCore.App.Runtime.NativeAOT.linux-x64", "version": "[10.0.14, 10.0.14]"},
   {"name": "Microsoft.NETCore.App.Runtime.NativeAOT.win-x64", "version": "[10.0.14, 10.0.14]"}]}}}}
JSON
  cat > "$dir/obj/Keypaste.App/project.assets.json" <<'JSON'
{"targets": {
  "net10.0/linux-x64": {"Native.Linux/2.0.0": {"type": "package", "native": {"runtimes/linux-x64/native/libn.so": {}}}},
  "net10.0-windows10.0.19041.0/win-x64": {"Win.Only/3.0.0": {"type": "package", "runtime": {"lib/net10.0/Win.dll": {}}}}},
 "project": {"frameworks": {
   "net10.0": {"downloadDependencies": [{"name": "Microsoft.NETCore.App.Runtime.linux-x64", "version": "[10.0.14, 10.0.14]"}]},
   "net10.0-windows10.0.19041.0": {"downloadDependencies": [
     {"name": "Microsoft.NETCore.App.Runtime.win-x64", "version": "[10.0.14, 10.0.14]"},
     {"name": "Microsoft.Windows.SDK.NET.Ref", "version": "[10.0.19041.57, 10.0.19041.57]"}]}}}}
JSON

  package() {
    local name="$1" version="$2" license="$3" lower
    lower="$(printf '%s' "$name" | tr '[:upper:]' '[:lower:]')"
    mkdir -p "$dir/nuget/$lower/$version"
    printf '\357\273\277<?xml version="1.0"?>\n<package><metadata>\n%s\n<copyright>Copyright %s &amp; friends</copyright>\n</metadata></package>\n' \
      "$license" "$name" > "$dir/nuget/$lower/$version/$lower.nuspec"
  }
  local mit='<license type="expression">MIT</license>'
  package Cli.Dep 1.0.0 "$mit"
  package Native.Linux 2.0.0 "$mit"
  package Win.Only 3.0.0 '<licenseUrl>https://example.test/terms</licenseUrl>'
  local rid
  for rid in linux-x64 win-x64; do
    package "Microsoft.NETCore.App.Runtime.NativeAOT.$rid" 10.0.14 "$mit"
    package "Microsoft.NETCore.App.Runtime.$rid" 10.0.14 "$mit"
    printf 'The MIT License\r\nsame text\r\n' > "$dir/nuget/microsoft.netcore.app.runtime.$rid/10.0.14/LICENSE.TXT"
  done
  printf '\357\273\277The MIT License\nsame text\n' > "$dir/nuget/microsoft.netcore.app.runtime.nativeaot.linux-x64/10.0.14/license.txt"
  printf 'bundled notices\n' > "$dir/nuget/native.linux/2.0.0/THIRD-PARTY-NOTICES.txt"
  package Microsoft.Windows.SDK.NET.Ref 10.0.19041.57 '<licenseUrl>https://example.test/sdk</licenseUrl>'

  printf '# Notices\n\n## Hand written\n\nKeep this sentence.\n\n%s\n%s\n' "$BEGIN_MARK" "$END_MARK" > "$NOTICES_FILE"

  expect_ok() {
    bash "$self" "$@" > "$dir/out" 2>&1 || { cat "$dir/out" >&2; die "selftest: expected '$*' to pass"; }
  }
  # <text the failure must print> <args...>
  expect_failure() {
    local needle="$1"
    shift
    if bash "$self" "$@" > "$dir/out" 2>&1; then die "selftest: expected '$*' to fail"; fi
    grep -qF -- "$needle" "$dir/out" || { cat "$dir/out" >&2; die "selftest: '$*' failed without saying '$needle'"; }
  }

  expect_ok generate
  grep -qF 'FLAG: Win.Only 3.0.0 gives only a licence URL' "$dir/out" || die 'selftest: a URL-only licence was not flagged'
  grep -qxF 'Keep this sentence.' "$NOTICES_FILE" || die 'selftest: generate lost the hand-written text'
  grep -qF '| Cli.Dep | 1.0.0 | CLI; Desktop | no | MIT | Copyright Cli.Dep & friends |' "$NOTICES_FILE" \
    || die 'selftest: a shared package is not listed for both products'
  grep -qF '| Native.Linux | 2.0.0 | Desktop (linux-x64) | yes | MIT |' "$NOTICES_FILE" \
    || die 'selftest: a one-platform native package is not listed for that platform'
  if grep -qF 'Analyzer.Only' "$NOTICES_FILE"; then die 'selftest: a package with only placeholder assets was listed'; fi
  [ "$(grep -c '^The MIT License$' "$NOTICES_FILE")" -eq 1 ] || die 'selftest: one licence text with different line endings appears twice'
  grep -qxF 'bundled notices' "$NOTICES_FILE" || die 'selftest: a bundled notices file was not carried'
  cp "$NOTICES_FILE" "$dir/first"
  expect_ok generate
  cmp -s "$NOTICES_FILE" "$dir/first" || die 'selftest: generate is not stable'

  expect_ok check cli "$NOTICES_FILE"
  expect_ok check desktop "$NOTICES_FILE"

  grep -vF '| Cli.Dep |' "$dir/first" > "$dir/missing.md"
  expect_failure 'Cli.Dep' check cli "$dir/missing.md"
  expect_failure 'shipped but not listed' check desktop "$dir/missing.md"
  grep -vF '| Native.Linux |' "$dir/first" > "$dir/missing-native.md"
  expect_failure 'Native.Linux' check desktop "$dir/missing-native.md"
  sed 's/| Cli.Dep | 1.0.0 |/| Cli.Dep | 1.0.1 |/' "$dir/first" > "$dir/version.md"
  expect_failure 'shipped but not listed' check cli "$dir/version.md"
  sed 's/^| Cli.Dep | 1.0.0 | CLI; Desktop |/| Cli.Dep | 1.0.0 | Desktop |/' "$dir/first" > "$dir/product.md"
  expect_failure 'shipped but not listed' check cli "$dir/product.md"
  awk -v end="$END_MARK" '$0 == end { print "| Stale.Row | 1.0.0 | CLI | no | MIT | x | y |" } { print }' "$dir/first" > "$dir/extra.md"
  expect_failure 'listed but not shipped' check cli "$dir/extra.md"
  printf '# Nothing generated here\n' > "$dir/none.md"
  expect_failure 'generated section' check cli "$dir/none.md"

  printf '{"targets": {"net10.0/linux-x64": {}}, "project": {"frameworks": {"net10.0": {"downloadDependencies": []}}}}\n' > "$dir/obj/Keypaste.Cli/project.assets.json"
  expect_failure 'no longer knows' check cli "$NOTICES_FILE"

  echo 'third-party-notices: selftest passed.'
}

case "${1:-}" in
  generate) generate ;;
  check)
    [ $# -eq 3 ] || die 'usage: third-party-notices.sh check <cli|desktop> <notices-file>'
    check "$2" "$3"
    ;;
  --selftest) selftest ;;
  *) die 'usage: third-party-notices.sh generate | check <cli|desktop> <notices-file> | --selftest' ;;
esac
