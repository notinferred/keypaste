#!/usr/bin/env python3
"""Vendors the Simple Icons keypaste draws and writes src/Keypaste.App/Theme/ServiceIcons.axaml from them.

Each icon becomes a StreamGeometry keyed Service.<slug> on Simple Icons' 24-unit grid, filled with the
non-zero rule its SVG uses, and its brand colour a Color keyed ServiceColor.<slug>. Draw them with
Controls/Monogram, which ItemMarks tells which service an item's website belongs to.

    python scripts/simple-icons-to-axaml.py                    # regenerate from third_party/simple-icons
    python scripts/simple-icons-to-axaml.py --from <package>   # first vendor ICONS from an unpacked simple-icons npm package

third_party/simple-icons/UPSTREAM.md says which package and how it was checked.
"""

import importlib.util
import json
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDORED = ROOT / "third_party" / "simple-icons"
TARGET = ROOT / "src" / "Keypaste.App" / "Theme" / "ServiceIcons.axaml"

# The services ItemMarks matches; no other password manager's mark is drawn.
ICONS = """
airbnb anthropic apple asana atlassian auth0 backblaze bitbucket bluesky cashapp circleci claude cloudflare coinbase datadog
digitalocean discord docker dropbox duckduckgo ebay epicgames etsy facebook figma firebase flydotio github gitlab gmail
godaddy google grafana hashicorp hetzner hubspot icloud instagram linear mailchimp mailgun mastodon medium miro mongodb
namecheap neon netflix netlify notion npm okta ovh pagerduty patreon paypal pinterest planetscale playstation postgresql
proton railway reddit redis render resend revolut sentry shopify signal spotify steam stripe substack supabase tailscale
telegram terraform tiktok trello twitch uber venmo vercel vultr whatsapp wise wordpress x youtube zapier zoom
""".split()

_spec = importlib.util.spec_from_file_location("lucide", ROOT / "scripts" / "lucide-to-axaml.py")
_lucide = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_lucide)


def vendor(package):
    entries = {entry["slug"]: entry for entry in json.loads((package / "data" / "simple-icons.json").read_text(encoding="utf-8"))}
    missing = [slug for slug in ICONS if slug not in entries]
    if missing:
        raise SystemExit(f"the package has no icon for {', '.join(missing)}")
    licensed = [slug for slug in ICONS if "license" in entries[slug]]
    if licensed:
        raise SystemExit(f"{', '.join(licensed)} carry a licence of their own; only CC0 icons are vendored")
    icons = VENDORED / "icons"
    if icons.exists():
        shutil.rmtree(icons)
    icons.mkdir(parents=True)
    for slug in ICONS:
        shutil.copyfile(package / "icons" / f"{slug}.svg", icons / f"{slug}.svg")
    for name in ("LICENSE.md", "DISCLAIMER.md"):
        shutil.copyfile(package / name, VENDORED / name)
    data = [entries[slug] for slug in sorted(ICONS)]
    write(VENDORED / "simple-icons.json", json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as file:
        file.write(text)


def geometry(slug):
    svg = ET.fromstring((VENDORED / "icons" / f"{slug}.svg").read_text(encoding="utf-8"))
    paths = [child for child in svg if child.tag.split("}")[-1] == "path"]
    if len(paths) != 1:
        raise SystemExit(f"{slug}.svg holds {len(paths)} paths, not one")
    return "F1 " + _lucide.path_tokens(paths[0].attrib["d"])


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--from":
        vendor(Path(sys.argv[2]))
    elif len(sys.argv) != 1:
        raise SystemExit(__doc__)
    colours = {entry["slug"]: entry["hex"] for entry in json.loads((VENDORED / "simple-icons.json").read_text(encoding="utf-8"))}
    lines = [
        '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        "",
        "  <!-- Generated by scripts/simple-icons-to-axaml.py from third_party/simple-icons (CC0). Do not edit;",
        "       add a slug to the script and run it again. Brand icons are trademarks of their owners. -->",
        "",
    ]
    for slug in sorted(ICONS):
        lines.append(f'  <StreamGeometry x:Key="Service.{slug}">{geometry(slug)}</StreamGeometry>')
        lines.append(f'  <Color x:Key="ServiceColor.{slug}">#{colours[slug].upper()}</Color>')
    lines += ["", "</ResourceDictionary>", ""]
    write(TARGET, "\n".join(lines))
    print(f"wrote {len(ICONS)} icons to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
