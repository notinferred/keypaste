#!/usr/bin/env python3
"""Writes src/Keypaste.App/Resources/Strings.cs from Strings.resx: one read-only property per label.

The class is checked in rather than made during the build because `dotnet format` reads the sources with
nothing built, and a view's {x:Static res:Strings.Name} is what turns a missing label into a build error.
LanguageAndRegionTests holds the class and the file to the same names.
"""
import pathlib
import re
import xml.etree.ElementTree as ElementTree

resources = pathlib.Path(__file__).resolve().parent.parent / "src" / "Keypaste.App" / "Resources"
names = sorted(data.get("name") for data in ElementTree.parse(resources / "Strings.resx").getroot().findall("data"))

for name in names:
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name):
        raise SystemExit(f"{name} is not an identifier")

lines = [
    "using System.Globalization;",
    "using System.Resources;",
    "",
    "namespace Keypaste.App.Resources;",
    "",
    "/// <summary>The words people read, by name. Generated by scripts/generate-strings.py from Strings.resx.</summary>",
    "public static class Strings",
    "{",
    '    /// <summary>Where the words come from; a test swaps it to draw a language that does not exist.</summary>',
    '    internal static ResourceManager Manager { get; set; } = new("Keypaste.App.Resources.Strings", typeof(Strings).Assembly);',
    "",
]
lines += [f'    public static string {name} => Manager.GetString("{name}", CultureInfo.CurrentUICulture)!;' for name in names]
lines += ["}", ""]
(resources / "Strings.cs").write_bytes("\n".join(lines).encode())
print(f"{len(names)} labels")
